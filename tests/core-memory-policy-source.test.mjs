const read = path => readFileSync(new URL(path,import.meta.url),"utf8");
function expectedFixture(module,names) {
  const imports = module === "mem" ? 'import module mem from "atto.core/mem";' :
    names.map(n => 'import fnc '+n+' from "atto.core/'+module+'";').join("\n");
  const prefix = module === "mem" ? "mem." : "imports::";
  const lines = vectors.filter(v=>names.includes(v[0])).map(([name,args,want],i)=>
    "  if "+(typeof want==="boolean"?(want?"!":""):"")+prefix+name+"("+args.join(", ")+")"+
    (typeof want==="boolean"?"":" != "+want)+" then return "+(i+1)+"; fi");
  return "// Real linked Atto guest: original boundary vectors, independent failure exits.\n"+
    imports+"\npub fnc main(): int {\n"+lines.join("\n")+"\n  return 42;\n}\n";
}
test("all 63 original vectors are present in actual Atto guests",()=>{
  assert.equal(vectors.length,63);
  const seen = new Set();
  for(const [module,names] of Object.entries(groups)) {
    const source=read(module==="mem"?"../library/core/mem.atto":"../stdlib/core/"+module+".atto");
    const code=source.replace(/^\s*\/\/.*$/gm,"");
    for(const n of names) {
      assert.ok(!seen.has(n),n); seen.add(n);
      assert.ok(code.includes("pub fnc "+n+"("),n);
    }
    const actual=read("./fixtures/core-memory-policy-v1/"+module+".atto");
    assert.equal(actual,expectedFixture(module,names));
  }
  assert.equal(seen.size,14);
  assert.ok(vectors.every(v=>seen.has(v[0])));
});
test("changed expectation or missing branch cannot match the pinned fixture",()=>{
  const source=read("./fixtures/core-memory-policy-v1/mem.atto");
  for(const mutation of [source.replace("then return 1;","then return 99;"),
    source.replace(/^  if .*\n/m,""), source.replace("return 42;","return 0;")]){
    assert.notEqual(mutation,source);
    assert.notEqual(mutation,expectedFixture("mem",groups.mem));
  }
});
