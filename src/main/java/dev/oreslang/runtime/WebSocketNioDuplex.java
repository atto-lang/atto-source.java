package dev.oreslang.runtime;

import java.io.EOFException;
import java.io.IOException;
import java.io.InputStream;
import java.net.SocketTimeoutException;
import java.nio.ByteBuffer;
import java.nio.channels.ClosedByInterruptException;
import java.nio.channels.SelectionKey;
import java.nio.channels.Selector;
import java.nio.channels.SocketChannel;
import java.util.Objects;
import java.util.concurrent.TimeUnit;

/**
 * Single-read/single-write deadline-bound RFC6455 socket-channel transport.
 *
 * <p>The channel must already be connected, authorized and in nonblocking mode.
 * A read and a write may run concurrently on separate host I/O workers; the
 * caller must serialize writes and hold the AsyncNativeIo physical socket loan.
 * Selectors may park host I/O workers, NEVER Oreslang actor or CONTROL carriers.
 * Closing the channel aborts either in-flight operation. No guest authority.</p>
 */
final class WebSocketNioDuplex {
    private WebSocketNioDuplex() { }

    static WebSocketFrameCodec.Frame readClientFrame(
            SocketChannel channel, int maxFrameBytes, int deadlineMillis)
            throws IOException {
        requireNonblocking(channel);
        long deadline = deadlineAfterMillis(deadlineMillis);
        try (Selector selector = Selector.open()) {
            channel.register(selector, SelectionKey.OP_READ);
            InputStream input = new InputStream() {
                @Override public int read() throws IOException {
                    byte[] one = new byte[1];
                    int n = read(one, 0, 1);
                    return n < 0 ? -1 : one[0] & 0xff;
                }

                @Override public int read(byte[] dst, int off, int len)
                        throws IOException {
                    Objects.requireNonNull(dst, "frame destination");
                    Objects.checkFromIndexSize(off, len, dst.length);
                    if (len == 0) return 0;
                    ByteBuffer bytes = ByteBuffer.wrap(dst, off, len);
                    for (;;) {
                        requireBeforeDeadline(deadline);
                        int n = channel.read(bytes);
                        if (n != 0) {
                            requireBeforeDeadline(deadline);
                            return n;
                        }
                        waitReady(selector, deadline);
                    }
                }

                // This input is a borrowed channel view, not a socket owner.
                @Override public void close() { }
            };
            return WebSocketFrameCodec.readClientFrame(input, maxFrameBytes);
        }
    }

    /** Emit a canonical unmasked server frame, with NO concatenated copy. */
    static void writeServerFrame(SocketChannel channel, boolean fin, int opcode,
            byte[] payload, int maxFrameBytes, int deadlineMillis)
            throws IOException {
        requireNonblocking(channel);
        Objects.requireNonNull(payload, "frame payload");
        // The strict Frame constructor checks opcode, CONTROL shape, UTF-8,
        // close codes and payload ownership. Bound before it clones bytes.
        if (maxFrameBytes < 1
                || maxFrameBytes > WebSocketFrameCodec.MAX_CONFIGURED_PAYLOAD_BYTES
                || payload.length > maxFrameBytes) {
            throw new IllegalArgumentException("WebSocket outbound frame exceeds limit");
        }
        var validated = new WebSocketFrameCodec.Frame(fin, opcode, payload);
        int count = validated.payloadUnsafe().length;
        ByteBuffer header = ByteBuffer.allocate(14);
        header.put((byte) ((fin ? 0x80 : 0) | opcode));
        if (count <= 125) {
            header.put((byte) count);
        } else if (count <= 0xffff) {
            header.put((byte) 126);
            header.putShort((short) count);
        } else {
            header.put((byte) 127);
            header.putLong(count);
        }
        header.flip();
        ByteBuffer body = ByteBuffer.wrap(validated.payloadUnsafe());
        writeFully(channel, new ByteBuffer[] {header, body},
                deadlineAfterMillis(deadlineMillis));
    }

    /** Upgrade response only: bounded, transport-generated bytes. */
    static void writeOpeningResponse(SocketChannel channel, byte[] response,
            long absoluteDeadlineNanos) throws IOException {
        requireNonblocking(channel);
        Objects.requireNonNull(response, "opening response");
        if (response.length < 1 || response.length > 4096) {
            throw new IllegalArgumentException("invalid bounded HTTP 101 response");
        }
        writeFully(channel, new ByteBuffer[] {ByteBuffer.wrap(response)},
                absoluteDeadlineNanos);
    }

    private static void writeFully(SocketChannel channel, ByteBuffer[] buffers,
            long deadline) throws IOException {
        try (Selector selector = Selector.open()) {
            channel.register(selector, SelectionKey.OP_WRITE);
            while (hasRemaining(buffers)) {
                requireBeforeDeadline(deadline);
                long count = channel.write(buffers);
                requireBeforeDeadline(deadline);
                if (count == 0) waitReady(selector, deadline);
            }
        }
    }

    private static boolean hasRemaining(ByteBuffer[] buffers) {
        for (ByteBuffer buffer : buffers) {
            if (buffer.hasRemaining()) return true;
        }
        return false;
    }

    private static void waitReady(Selector selector, long deadline)
            throws IOException {
        if (Thread.currentThread().isInterrupted()) {
            throw new ClosedByInterruptException();
        }
        long remaining = deadline - System.nanoTime();
        if (remaining <= 0) {
            throw new SocketTimeoutException("WebSocket NIO absolute deadline expired");
        }
        // Never pass zero to Selector.select: zero means infinite wait.
        long millis = Math.max(1L, (remaining + 999_999L) / 1_000_000L);
        selector.select(millis);
        requireBeforeDeadline(deadline);
        if (Thread.currentThread().isInterrupted()) {
            throw new ClosedByInterruptException();
        }
    }

    static long deadlineAfterMillis(int deadlineMillis) {
        if (deadlineMillis < 1 || deadlineMillis > 30_000) {
            throw new IllegalArgumentException("invalid WebSocket I/O deadline");
        }
        return System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(deadlineMillis);
    }

    static void requireBeforeDeadline(long deadline) throws SocketTimeoutException {
        if (deadline - System.nanoTime() <= 0) {
            throw new SocketTimeoutException("WebSocket NIO absolute deadline expired");
        }
    }

    private static void requireNonblocking(SocketChannel channel) {
        Objects.requireNonNull(channel, "WebSocket channel");
        if (channel.isBlocking()) {
            throw new IllegalArgumentException("WebSocket channel must be nonblocking");
        }
    }
}
